/// <summary>
/// Metadata for extracted fields including document, page, and row level info.
/// </summary>
[JsonConverter(typeof(JsonModelConverter<ExtractedFieldMetadata, ExtractedFieldMetadataFromRaw>))]
public sealed record class ExtractedFieldMetadata : JsonModel
{
    /// <summary>
    /// Per-field metadata keyed by field name from your schema. Scalar fields (e.g.
    /// `vendor`) map to a FieldMetadataEntry with citation and confidence. Array
    /// fields (e.g. `items`) map to a list where each element contains per-sub-field
    /// FieldMetadataEntry objects, indexed by array position. Nested objects contain
    /// sub-field entries recursively.
    /// </summary>
    public IReadOnlyDictionary<string, DocumentMetadata?>? DocumentMetadata
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableClass<FrozenDictionary<string, DocumentMetadata?>>(
                "document_metadata"
            );
        }
        init
        {
            this._rawData.Set<FrozenDictionary<string, DocumentMetadata?>?>(
                "document_metadata",
                value == null ? null : FrozenDictionary.ToFrozenDictionary(value)
            );
        }
    }

    /// <summary>
    /// Per-page metadata when extraction_target is per_page
    /// </summary>
    public IReadOnlyList<IReadOnlyDictionary<string, PageMetadata?>>? PageMetadata
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableStruct<
                ImmutableArray<FrozenDictionary<string, PageMetadata?>>
            >("page_metadata");
        }
        init
        {
            this._rawData.Set<ImmutableArray<FrozenDictionary<string, PageMetadata?>>?>(
                "page_metadata",
                value == null
                    ? null
                    : ImmutableArray.ToImmutableArray(
                        Enumerable.Select(
                            value,
                            (item) => FrozenDictionary.ToFrozenDictionary(item)
                        )
                    )
            );
        }
    }

    /// <summary>
    /// Per-row metadata when extraction_target is per_table_row
    /// </summary>
    public IReadOnlyList<IReadOnlyDictionary<string, RowMetadata?>>? RowMetadata
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableStruct<
                ImmutableArray<FrozenDictionary<string, RowMetadata?>>
            >("row_metadata");
        }
        init
        {
            this._rawData.Set<ImmutableArray<FrozenDictionary<string, RowMetadata?>>?>(
                "row_metadata",
                value == null
                    ? null
                    : ImmutableArray.ToImmutableArray(
                        Enumerable.Select(
                            value,
                            (item) => FrozenDictionary.ToFrozenDictionary(item)
                        )
                    )
            );
        }
    }

    /// <inheritdoc/>
    public override void Validate()
    {
        if (this.DocumentMetadata != null)
        {
            foreach (var item in this.DocumentMetadata.Values)
            {
                item?.Validate();
            }
        }
        foreach (var item in this.PageMetadata ?? [])
        {
            foreach (var item1 in item.Values)
            {
                item1?.Validate();
            }
        }
        foreach (var item in this.RowMetadata ?? [])
        {
            foreach (var item1 in item.Values)
            {
                item1?.Validate();
            }
        }
    }

    public ExtractedFieldMetadata() { }

#pragma warning disable CS8618
    [SetsRequiredMembers]
    public ExtractedFieldMetadata(ExtractedFieldMetadata extractedFieldMetadata)
        : base(extractedFieldMetadata) { }
#pragma warning restore CS8618

    public ExtractedFieldMetadata(IReadOnlyDictionary<string, JsonElement> rawData)
    {
        this._rawData = new(rawData);
    }

#pragma warning disable CS8618
    [SetsRequiredMembers]
    ExtractedFieldMetadata(FrozenDictionary<string, JsonElement> rawData)
    {
        this._rawData = new(rawData);
    }
#pragma warning restore CS8618

    /// <inheritdoc cref="ExtractedFieldMetadataFromRaw.FromRawUnchecked"/>
    public static ExtractedFieldMetadata FromRawUnchecked(
        IReadOnlyDictionary<string, JsonElement> rawData
    )
    {
        return new(FrozenDictionary.ToFrozenDictionary(rawData));
    }
}

